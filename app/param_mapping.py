"""오퍼레이터용 0~100 스케일 → CV 원본값 매핑.

각 함수는 슬라이더 값(0~100)을 받아 검출기 내부 파라미터로 변환한다.
스펙 §4.2 매핑 표의 앵커값을 만족하도록 설계됨.
"""
import math


def sensitivity_to_min_t(v: int) -> float:
    """감도 0~100 → blob 검출기의 t-통계량 하한. 50이 default(25)에 앵커.

    t는 면적 가중 t-통계량이라 스케일·극성에 무관하고 단조롭다. 이 값 하나가
    정밀도/재현율 교환을 그대로 통제하므로 오퍼레이터 감도 슬라이더에 직결된다.

    엔드포인트 실측 곡선 (라벨 39장, 정답 1,886개 · 접시별 극성 자동 판정 +
    solidity 0.75 반영 후):
        t=35 → 정밀도 93.8% / 재현율 59.5%
        t=25 → 86.4% / 65.2%   ← default (감도 50)
        t=20 → 79.9% / 67.8%
        t=15 → 70.5% / 71.4%
        t=12 → 62.9% / 73.5%
    감도를 올리면 t가 내려가 흐린 콜로니까지 잡고(재현율↑) 오검출이 늘어난다.

    **앵커가 35에서 25로 내려갔다.** 접시별 극성 자동 판정이 정밀도를 5.3%p
    벌어줬고(§8.4e), 그 여유를 재현율로 바꾸는 것이 이 프로젝트의 용도(피킹
    대상 확보)에 맞다는 판단이다. 세션 시작 대비 재현율 57.6 → 65.2%,
    정밀도 91.4 → 86.4%.

    앵커를 옮길 때는 **config.BLOB_MIN_T 와 반드시 함께** 움직여야 한다.
    어긋나면 요청에 sensitivity 를 넣은 클라이언트와 넣지 않은 클라이언트가
    다른 감도로 동작하고, 그 차이는 눈으로 알아채기 어렵다.

    0~50 구간 linear: 90 → 25 (매우 엄격 → default)
    50~100 구간 linear: 25 → 12 (default → 매우 민감)
    """
    if v <= 50:
        return 90.0 - (v / 50) * 65.0
    return 25.0 - ((v - 50) / 50) * 13.0


def edge_to_margin_px(v: int) -> int:
    """벽 여백 0~100 → 픽셀. 40이 현재 default(60px)에 앵커.

    edge_margin = v · 1.5  (linear, 0~150px)
    """
    return round(v * 1.5)
