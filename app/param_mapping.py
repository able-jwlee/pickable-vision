"""오퍼레이터용 0~100 스케일 → CV 원본값 매핑.

각 함수는 슬라이더 값(0~100)을 받아 검출기 내부 파라미터로 변환한다.
스펙 §4.2 매핑 표의 앵커값을 만족하도록 설계됨.
"""
import math


def sensitivity_to_min_t(v: int) -> float:
    """감도 0~100 → blob 검출기의 t-통계량 하한. 50이 default(20)에 앵커.

    t는 면적 가중 t-통계량이라 스케일·극성에 무관하고 단조롭다. 이 값 하나가
    정밀도/재현율 교환을 그대로 통제하므로 오퍼레이터 감도 슬라이더에 직결된다.

    엔드포인트 실측 곡선 (라벨 39장, 정답 1,886개 · 현재 설정):
        감도 43 → t=30 → 정밀도 89.0% / 재현율 70.9%
        감도 46 → t=25 → 86.7% / 73.3%   (F1 최고 79.4)
        감도 50 → t=20 → 82.2% / 75.7%   ← default
        감도 81 → t=15 → 73.5% / 77.3%
    감도를 올리면 t가 내려가 흐린 콜로니까지 잡고(재현율↑) 오검출이 늘어난다.

    앵커는 **감도 50 = config.BLOB_MIN_T** 이고, 앵커를 옮길 때는 그 상수와
    **반드시 함께** 움직여야 한다. 어긋나면 요청에 sensitivity 를 넣은
    클라이언트와 넣지 않은 클라이언트가 다른 감도로 동작하고, 그 차이는 눈으로
    알아채기 어렵다 (tests/test_param_mapping.py 가 관계를 고정한다).

    0~50 구간 linear: 90 → 20 (매우 엄격 → default)
    50~100 구간 linear: 20 → 12 (default → 매우 민감)

    **구간이 비대칭이다.** 아래쪽은 한 칸이 t 1.4, 위쪽은 0.16 씩 움직인다.
    실측점이 있는 구간은 43~81 뿐이고, 그 밖(0~43 = t 90~30)은 측정한 적이
    없는 극단이다. 오퍼레이터 UI 는 슬라이더를 40~85 로 좁히거나 그 밖을
    "측정 범위 밖" 으로 표시할 것 — docs/react-integration.md 참조.
    """
    if v <= 50:
        return 90.0 - (v / 50) * 70.0
    return 20.0 - ((v - 50) / 50) * 8.0


def edge_to_margin_px(v: int) -> int:
    """벽 여백 0~100 → 픽셀. 0 = 제한 없음(서버 기본값과 같다).

    edge_margin = v · 1.5  (linear, 0~150px)

    **앵커가 없다.** config.PICK_EDGE_MARGIN 이 0 이므로 요청에 edge_margin 을
    넣지 않은 클라이언트와 0 을 넣은 클라이언트가 같게 동작한다. (이 docstring
    은 한때 "40이 default(60px)에 앵커" 라고 적혀 있었는데, 그 60px 기본값은
    피킹 필터를 끄면서 사라졌다.)

    단위가 **원본 픽셀**이라 해상도에 의존한다 — 카메라를 바꾸면 같은 슬라이더
    값이 다른 물리 여백을 뜻한다. 그리고 mask_walls=False 면 무동작이다.
    """
    return round(v * 1.5)
